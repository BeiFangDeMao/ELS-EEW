import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {Workbook} from '@oai/artifact-tool';
const here=path.dirname(fileURLToPath(import.meta.url));
const pointer=JSON.parse(await fs.readFile(path.join(here,'accuracy_2p88_results/latest_run.json'),'utf8'));
const folder=pointer.directory;
const data=JSON.parse(await fs.readFile(path.join(folder,'evaluation.json'),'utf8'));
const headers=['Task','Model','MAE','MSE','MedAE','R²'];
const expected=[headers,...data.rows.map(r=>[r.Task,r.Model,r.MAE,r.MSE,r.MedAE,r.R2])];
if(expected.length!==9||data.records!==51772)throw new Error('Unexpected table/cohort');
const book=Workbook.create();const sheet=book.worksheets.add('Accuracy');
sheet.getRange('A1:F9').values=expected;
book.recalculate();
const actual=sheet.getRange('A1:F9').values;
if(JSON.stringify(actual)!==JSON.stringify(expected))throw new Error('Values changed');
const escape=v=>v===null?'NaN':/[",\r\n]/.test(String(v))?'"'+String(v).replaceAll('"','""')+'"':String(v);
await fs.writeFile(path.join(folder,'accuracy_summary_2p88s.csv'),'\ufeff'+actual.map(r=>r.map(escape).join(',')).join('\r\n')+'\r\n','utf8');
console.log(JSON.stringify({output:path.join(folder,'accuracy_summary_2p88s.csv'),rows:8,full_precision:true}));
